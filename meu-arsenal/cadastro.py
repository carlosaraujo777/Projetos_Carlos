print("--- CALCULADORA DE SOMA ---")

# Recebe os números (e já converte pra número inteiro)
numero1 = int(input("Digite o primeiro número: "))
numero2 = int(input("Digite o segundo número: "))

# Faz a conta
resultado = numero1 + numero2

# Mostra o resultado
print("A soma de " + str(numero1) + " + " + str(numero2) + " é igual a " + str(resultado))